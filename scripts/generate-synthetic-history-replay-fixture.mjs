#!/usr/bin/env node
/**
 * Deterministic synthetic SDK history records for replay lifecycle harnesses.
 * No private content — padded assistant blob only.
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const TARGET_RECORD_COUNT = 52;
const LARGE_RECORD_BYTES = 800 * 1024;
const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outPath = path.join(projectRoot, 'tests/fixtures/synthetic-history-replay-records.json');

/** @param {number} index */
function baseTimestamp(index) {
  const base = Date.parse('2026-10-01T10:00:00.000Z');
  return new Date(base + index * 1000).toISOString();
}

/** @returns {unknown[]} */
function buildRecords() {
  /** @type {unknown[]} */
  const records = [];
  const paddingUnit = 'x'.repeat(1024);
  let largeBody = '';
  while (Buffer.byteLength(largeBody, 'utf8') < LARGE_RECORD_BYTES) {
    largeBody += paddingUnit;
  }
  largeBody = largeBody.slice(0, LARGE_RECORD_BYTES);
  for (let index = 0; index < TARGET_RECORD_COUNT; index += 1) {
    const isUser = index % 3 === 0;
    const isLarge = index === Math.floor(TARGET_RECORD_COUNT / 2);
    if (isLarge) {
      records.push({
        type: 'assistant',
        message: `[synthetic-large-report ${LARGE_RECORD_BYTES} bytes]\n${largeBody}`,
        createdAt: baseTimestamp(index),
      });
      continue;
    }
    records.push({
      type: isUser ? 'user' : 'assistant',
      message: isUser
        ? `Synthetic user turn ${index + 1}.`
        : `Synthetic assistant reply ${index + 1}.`,
      createdAt: baseTimestamp(index),
    });
  }
  return records;
}

const records = buildRecords();
const doc = {
  description: 'Synthetic SDK history records for replay lifecycle baseline (no private content).',
  recordCount: records.length,
  records,
  notes:
    'Generated by scripts/generate-synthetic-history-replay-fixture.mjs; includes one ~800KB assistant record.',
};

writeFileSync(outPath, `${JSON.stringify(doc, null, 2)}\n`, 'utf8');
process.stdout.write(`Wrote ${records.length} records to ${outPath}\n`);
