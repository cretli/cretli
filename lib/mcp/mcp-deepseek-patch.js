/**
 * DeepSeek cordis overlay for a single managed MCP bridge.
 */

import fs from 'fs';
import path from 'path';
import { writeJsonAtomic } from '../persist/atomic-write.js';
import { resolveDataPath } from '../runtime-paths.js';

/**
 * @param {{ command: string, args: string[], env: Record<string, string> } | null} bridge
 * @returns {string | null}
 */
export function writeDeepSeekMcpPatch(bridge) {
  if (!bridge) return null;
  const dir = resolveDataPath('mcp');
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
  const filePath = path.join(dir, 'dsh-mcp-bridge.yml');
  const envLines = Object.entries(bridge.env || {})
    .map(([key, value]) => `            ${JSON.stringify(key)}: ${JSON.stringify(value)}`)
    .join('\n');
  const argsLines = (bridge.args || []).map((part) => `          - ${JSON.stringify(part)}`).join('\n');
  const yaml = [
    '# Generated by Cretli. Do not edit.',
    '- insert:',
    '    - id: cretli-mcp-bridge',
    "      name: '@deepseek-ai/dsh-mcp-client'",
    '      inject: [tools]',
    '      config:',
    '        transport: stdio',
    '        serverName: cretli_bridge',
    `        command: ${JSON.stringify(bridge.command)}`,
    '        args:',
    argsLines,
    '        env:',
    envLines || '          {}',
    '        failOnStartupError: false',
    '',
  ].join('\n');
  fs.writeFileSync(filePath, yaml, 'utf8');
  return filePath;
}

/**
 * @param {string} filePath
 */
export function touchDeepSeekMcpPatchMeta(filePath) {
  writeJsonAtomic(`${filePath}.meta.json`, { updatedAt: new Date().toISOString() });
}
