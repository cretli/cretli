/**
 * Generated DSH sdk-profile overlay: LAN-friendly web_fetch, hide read_image
 * on text-only models, and declare image input on V4.1 Flash (stock DSH only
 * marks deepseek-v4-flash-vision-exp).
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolveDataPath } from '../runtime-paths.js';
import { listDeepSeekDshCatalogModels } from './deepseek-model-ids.js';
import { DEEPSEEK_COMPACTION_DEFAULTS } from './deepseek-compaction-config.js';

const DEEPSEEK_LIB_DIR = path.dirname(fileURLToPath(import.meta.url));

export const DEEPSEEK_RUNTIME_PLUGIN_PATH = path.join(DEEPSEEK_LIB_DIR, 'dsh-runtime-plugin.js');
export const DEEPSEEK_RUNTIME_PATCH_NAME = 'dsh-runtime.cordis.patch.yml';

/**
 * @param {ReturnType<typeof listDeepSeekDshCatalogModels>} models
 * @returns {string}
 */
function formatLlmDeepSeekModelsYaml(models) {
  return models.map((model) => {
    const lines = [
      `      - id: ${JSON.stringify(model.id)}`,
      `        name: ${JSON.stringify(model.name)}`,
      `        contextWindow: ${model.contextWindow}`,
      '        inputModalities:',
    ];
    for (const modality of model.inputModalities) {
      lines.push(`          - ${modality}`);
    }
    return lines.join('\n');
  }).join('\n');
}

/**
 * Format the native compaction policy row. DSH replaces the targeted row's
 * whole config, so the two ratios are restated completely.
 *
 * @param {{ thresholdRatio: number, retainRatio: number }} compaction
 * @returns {string}
 */
function formatDeepSeekCompactionYaml(compaction) {
  return [
    '- id: compaction-basic',
    '  config:',
    `    thresholdRatio: ${compaction.thresholdRatio}`,
    `    retainRatio: ${compaction.retainRatio}`,
  ].join('\n');
}

/**
 * Write the Cretli runtime overlay. Plugin `name` must be a string file URL:
 * DSH `!!js` is an expression node (`{ __jsExpr }`), and the loader calls
 * `name.startsWith`.
 *
 * @param {{ compaction?: { thresholdRatio: number, retainRatio: number } }} [options]
 * @returns {string}
 */
export function writeDeepSeekRuntimePatch(options = {}) {
  const dir = resolveDataPath('mcp');
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
  const filePath = path.join(dir, DEEPSEEK_RUNTIME_PATCH_NAME);
  const pluginHref = pathToFileURL(DEEPSEEK_RUNTIME_PLUGIN_PATH).href;
  const compaction = options.compaction || DEEPSEEK_COMPACTION_DEFAULTS;
  const yaml = [
    '# Generated by Cretli. Do not edit.',
    '- id: web-fetch-http',
    '  disabled: true',
    '',
    '- id: llm-deepseek',
    '  config:',
    '    models:',
    formatLlmDeepSeekModelsYaml(listDeepSeekDshCatalogModels()),
    '',
    '# Lower DSH native auto-compaction from its stock 0.8 of the declared',
    '# context window so the harness keeps long chats bounded on its own.',
    formatDeepSeekCompactionYaml(compaction),
    '',
    '- insert:',
    '    - id: cretli-dsh-runtime',
    `      name: ${JSON.stringify(pluginHref)}`,
    '      inject: [web, agents]',
    '',
  ].join('\n');
  fs.writeFileSync(filePath, yaml, 'utf8');
  return filePath;
}
