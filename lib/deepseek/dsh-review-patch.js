/**
 * Cordis overlay forcing read-only sandbox and headless approval policy for review runs.
 *
 * Loader patches replace a row's whole `config` (no merge), so every required
 * key must be restated: `sandbox-policy` needs `workspaceRoot`. The stock
 * `permission` presets have no read-only + never pair and refuse to boot
 * without a matching `defaultPreset` (surfaced by the SDK as Cordis
 * `cannot create effect on inactive context`).
 */

import fs from 'fs';
import path from 'path';
import { resolveDataPath } from '../runtime-paths.js';

const REVIEW_PATCH_RELATIVE = path.join('mcp', 'dsh-review-readonly.yml');
const REVIEW_PRESET = 'cretli-review';

const REVIEW_PATCH_YAML = [
  '# Generated by Cretli. Do not edit.',
  '- id: sandbox-policy',
  '  config:',
  '    mode: read-only',
  '    workspaceRoot: !!js process.cwd()',
  '',
  '- id: approval',
  '  config:',
  '    policy: never',
  '',
  '- id: permission',
  '  config:',
  '    presets:',
  `      ${REVIEW_PRESET}:`,
  '        sandbox: read-only',
  '        approval: never',
  `        name: ${REVIEW_PRESET}`,
  '        description: Read-only review run without approval prompts.',
  `    defaultPreset: ${REVIEW_PRESET}`,
  '',
].join('\n');

/**
 * @returns {string}
 */
export function writeDeepSeekReviewReadOnlyPatch() {
  const filePath = resolveDataPath(REVIEW_PATCH_RELATIVE);
  const dir = path.dirname(filePath);
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(filePath, REVIEW_PATCH_YAML, 'utf8');
  return filePath;
}
